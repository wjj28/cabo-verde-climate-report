export const ui: Record<Lang, UI> = { en, fr, zh };
export const t = (lang: Lang) => ui[lang];

/** Number formatting per language (decimal comma in fr/pt, Arabic keeps Western digits for data clarity). */
export const fmt = (lang: Lang, n: number, digits = 1) =>
  new Intl.NumberFormat(lang === 'ar' ? 'ar-u-nu-latn' : lang, { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(n);

/** "Chapter 3" / "Chapitre 3" / "第3章" */
export const chapterLabel = (lang: Lang, n: number) => (lang === 'zh' ? `第${n}章` : `${ui[lang].chapter} ${n}`);

/** "Chapter 3: Title" with the punctuation each language expects. */
export const chapterTitle = (lang: Lang, n: number, title: string) =>
  `${chapterLabel(lang, n)}${lang === 'zh' ? '：' : lang === 'fr' ? ' : ' : ': '}${title}`;
